// Builds the drizzle/0001_seed.sql migration from the sample data that used to be hard-coded in the UI
// (tree members + links from scripts/sample-tree.js, news from the public news page).
// Usage: node scripts/build-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";

function extractArray(file, name) {
    const src = readFileSync(file, "utf8");
    const start = src.indexOf(`const ${name}`);
    if (start === -1) throw new Error(`${name} not found in ${file}`);
    const open = src.indexOf("[", src.indexOf("=", start));
    const close = src.indexOf("\n];", open);
    // The arrays are plain object literals, so they evaluate safely on their own.
    return new Function(`return ${src.slice(open, close + 2)}`)();
}

const q = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined || v === "" ? "NULL" : String(Number(v)));

const nodes = extractArray("scripts/sample-tree.js", "initialNodes");
const edges = extractArray("scripts/sample-tree.js", "initialEdges");
const newsItems = extractArray("src/app/(public)/news/page.tsx", "NEWS_ITEMS");

const serialById = new Map(nodes.map((node) => [node.id, node.data.serial]));
const out = [];

for (const { data } of nodes) {
    const birth = data.birthDate ?? {};
    // The sample gives every member a placeholder death date; keep it only for the deceased.
    const death = data.status === "deceased" ? data.deathDate ?? {} : {};
    out.push(
        `INSERT INTO members (serial_number, full_name, gender, status, generation_label, birth_year, birth_month, birth_day, birth_calendar, death_year, death_month, death_day, death_calendar) VALUES (` +
            [
                q(data.serial),
                q(data.label),
                q(data.gender),
                q(data.status),
                q(data.role),
                n(birth.year),
                n(birth.month),
                n(birth.day),
                q(birth.type ? birth.type.toLowerCase() : "hijri"),
                n(death.year),
                n(death.month),
                n(death.day),
                death.type ? q(death.type.toLowerCase()) : "NULL",
            ].join(", ") +
            `) ON CONFLICT (serial_number) DO NOTHING;`,
    );
}

for (const edge of edges) {
    out.push(
        `INSERT INTO relationships (parent_id, child_id) SELECT p.id, c.id FROM members p, members c ` +
            `WHERE p.serial_number = ${q(serialById.get(edge.source))} AND c.serial_number = ${q(serialById.get(edge.target))} ` +
            `ON CONFLICT (parent_id, child_id) DO NOTHING;`,
    );
}

const arabicMonths = {
    يناير: 1, فبراير: 2, مارس: 3, أبريل: 4, ابريل: 4, مايو: 5, يونيو: 6,
    يوليو: 7, أغسطس: 8, اغسطس: 8, سبتمبر: 9, أكتوبر: 10, اكتوبر: 10, نوفمبر: 11, ديسمبر: 12,
};
function toIsoDate(text) {
    const [day, monthName, year] = text.trim().split(/\s+/);
    const month = arabicMonths[monthName];
    if (!month) throw new Error(`Unknown month in "${text}"`);
    return `${year}-${String(month).padStart(2, "0")}-${String(Number(day)).padStart(2, "0")}`;
}

for (const item of newsItems) {
    out.push(
        `INSERT INTO news (slug, title, excerpt, category, status, published_at) VALUES (` +
            [q(`news-${item.id}`), q(item.title), q(item.excerpt), q(item.category), q("published"), q(toIsoDate(item.date))].join(", ") +
            `) ON CONFLICT (slug) DO NOTHING;`,
    );
}

// Runs once as a migration on deploy; ON CONFLICT keeps it harmless if rows already exist.
writeFileSync(
    "drizzle/0001_seed.sql",
    "-- Sample data generated by scripts/build-seed.mjs\n" + out.join("\n--> statement-breakpoint\n") + "\n",
);
console.log(`seed.sql: ${nodes.length} members, ${edges.length} links, ${newsItems.length} news`);
